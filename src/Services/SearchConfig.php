<?php

declare(strict_types=1);

namespace GafferSearch\Services;

use GafferSearch\Support\ConfigLocation;
use GafferSearch\Support\IndexSlug;
use GafferSearch\Support\ProtectedDir;
use GafferSearch\Support\Language\Languages;

/**
 * Writes the current site's config the no-WordPress endpoints read: index folder, token secret,
 * and the index-name → file-slug map. See ConfigLocation for where it lives and why.
 *
 * @internal Not part of the public API (see API.md): may change in any version.
 */
final class SearchConfig
{
    /**
     * The file's format. Bumped whenever its shape changes (2: indexes as name → language →
     * slug); a file with another format is rewritten on the next request (Bootstrap), so an
     * update that bypasses WordPress's updater (a deploy, a manual copy) can't leave the
     * endpoints reading a shape they no longer understand.
     */
    public const int FORMAT = 2;

    /**
     * The current site's file holds exactly what write() would write now. Checked on every
     * request: with several web servers each one has its own file (wp-content is per server),
     * so a settings change, a rotated secret or a new index made on one server reaches the
     * others on their next request.
     */
    public function isCurrent(): bool
    {
        $path = $this->path();
        if (!is_file($path)) {
            return false;
        }
        return (require $path) === $this->data();
    }

    public function __construct(
        private readonly SettingsService $settings,
        private readonly IndexRegistry $registry,
    ) {}

    public function path(): string
    {
        return ConfigLocation::forContentDir(WP_CONTENT_DIR, get_current_blog_id());
    }

    /**
     * Whether the endpoints can find the file without GAFFER_SEARCH_CONFIG_DIR: they derive the
     * content folder as the parent of the plugins folder, which holds when WP_PLUGIN_DIR sits
     * directly inside WP_CONTENT_DIR (WordPress's own default, and Bedrock's). The dashboard's
     * live endpoint check covers what this can't see (a symlinked plugin folder).
     */
    public function endpointsCanFindIt(): bool
    {
        if (ConfigLocation::fromEnvironment() !== null) {
            return true;
        }
        return untrailingslashit(wp_normalize_path(dirname(WP_PLUGIN_DIR)))
            === untrailingslashit(wp_normalize_path(WP_CONTENT_DIR));
    }

    public function write(): bool
    {
        $path = $this->path();
        $root = ConfigLocation::dirForContentDir(WP_CONTENT_DIR);
        $dir  = dirname($path);

        if (!ProtectedDir::ensure($dir)) {
            $this->fail("could not create {$dir}");
            return false;
        }
        ProtectedDir::ensure($root);

        $content = "<?php\n// Generated by Gaffer Search — do not edit; rewritten whenever its content changes.\nreturn "
            . var_export($this->data(), true) . ";\n"; // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_var_export

        $tmp     = $path . '.tmp-' . bin2hex(random_bytes(4));
        $written = file_put_contents($tmp, $content, LOCK_EX); // phpcs:ignore WordPress.WP.AlternativeFunctions.file_system_operations_file_put_contents
        if ($written === false || !rename($tmp, $path)) { // phpcs:ignore WordPress.WP.AlternativeFunctions.rename_rename -- atomic write; WP_Filesystem is not appropriate here
            @unlink($tmp); // phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged
            $this->fail("could not write {$path}");
            return false;
        }

        // The endpoints and isCurrent() read it with require: with opcache.validate_timestamps=0
        // OPcache would keep serving the old file. This only reaches this PHP's OPcache (a
        // write from the CLI doesn't reach PHP-FPM's): the next web request's isCurrent() reads
        // the stale copy, finds it differs and writes it again, from there.
        if (function_exists('opcache_invalidate')) {
            @opcache_invalidate($path, true); // phpcs:ignore WordPress.PHP.NoSilencedErrors.Discouraged -- restricted by opcache.restrict_api: nothing to do
        }
        return true;
    }

    /**
     * What the endpoints need, from the database and this server's settings. A request without
     * definitions (the active theme isn't on config/search.php yet: the live theme while a staged
     * copy is built and checked) keeps the indexes the file has: it changes nothing of the site's
     * search, as a build in such a request keeps the old index.
     *
     * @return array<string, mixed>
     */
    private function data(): array
    {
        $indexes = [];
        if ($this->registry->names() === [] && is_file($this->path())) {
            $current = require $this->path();
            $indexes = is_array($current) && ($current['format'] ?? null) === self::FORMAT && is_array($current['indexes'] ?? null) ? $current['indexes'] : [];
        }
        foreach ($this->registry->names() as $name) {
            // name → language → file slug; '' for the one file of a site without languages.
            foreach (Languages::codes() as $language) {
                $indexes[$name][ (string) $language] = IndexSlug::compute($name, $this->settings->searchSecret(), $language);
            }
        }

        return [
            'format'       => self::FORMAT,
            'index_dir'    => ConfigLocation::indexDirFor($this->path(), (string) $this->settings->get('index_dir'), WP_CONTENT_DIR),
            'token_secret' => $this->settings->tokenSecret(),
            'indexes'      => $indexes,
        ];
    }

    private function fail(string $reason): void
    {
        error_log("Gaffer Search: failed to write the endpoint config: {$reason}."); // phpcs:ignore WordPress.PHP.DevelopmentFunctions.error_log_error_log
    }
}
